"""Backtest: do 3rd/4th-down and pocket-time/pressure matchups beat the closing line?
Usage: python tools/situational_backtest.py DATA_DIR
Features use only games BEFORE each game (expanding, shrunk to league mean, prior-season blended)."""
import sys, glob, numpy as np, pandas as pd
D = sys.argv[1] if len(sys.argv) > 1 else "."
YEARS = [2022, 2023, 2024, 2025, 2026]
K = 8          # shrink games' worth toward league mean
PRIOR_W = 4    # prior-season games blended in

# ---- per team-game stats from pbp
rows = []
for y in YEARS:
    p = pd.read_csv(f"{D}/pbp{y}.csv.gz", low_memory=False)
    p = p[p.season_type == "REG"]
    pl = p[p.play_type.isin(["pass", "run"]) & (p.qb_kneel != 1) & (p.qb_spike != 1)]
    t3 = pl[pl.down == 3].groupby(["game_id", "posteam", "defteam"]).agg(t3_n=("first_down", "size"), t3_c=("first_down", "sum")).reset_index()
    f4 = p[(p.down == 4) & p.play_type.isin(["pass", "run", "punt", "field_goal"])]
    f4 = f4.assign(go=f4.play_type.isin(["pass", "run"]).astype(int))
    f4g = f4[f4.go == 1]
    a4 = f4.groupby(["game_id", "posteam"]).agg(f4_n=("go", "size"), f4_go=("go", "sum")).reset_index()
    c4 = f4g.groupby(["game_id", "posteam"]).agg(f4_c=("first_down", "sum")).reset_index()
    db = p[(p.pass_attempt == 1) | (p.sack == 1)]
    pr = db.groupby(["game_id", "posteam"]).agg(db_n=("play_id", "size"), sacks=("sack", "sum"), hits=("qb_hit", "sum")).reset_index()
    m = t3.merge(a4, on=["game_id", "posteam"], how="outer").merge(c4, on=["game_id", "posteam"], how="left").merge(pr, on=["game_id", "posteam"], how="left")
    m["season"] = y
    rows.append(m)
tg = pd.concat(rows).fillna(0)
g = pd.read_csv(f"{D}/games.csv")
g = g[(g.game_type == "REG") & g.season.isin(YEARS)][["game_id", "season", "week", "home_team", "away_team", "home_score", "away_score", "spread_line", "total_line"]]
# defteam for 4th/pr rows: map via game
tg = tg.merge(g[["game_id", "week", "home_team", "away_team"]], on="game_id")
tg["opp"] = np.where(tg.posteam == tg.home_team, tg.away_team, tg.home_team)
tg = tg.rename(columns={"posteam": "team"})

# NGS time to throw by team-week
n = pd.read_csv(f"{D}/ngs.csv.gz")
n = n[(n.week > 0) & n.season.isin(YEARS)]
ttt = n.groupby(["season", "week", "team_abbr"]).apply(lambda d: np.average(d.avg_time_to_throw, weights=d.attempts)).rename("ttt").reset_index().rename(columns={"team_abbr": "team"})
tg = tg.merge(ttt, on=["season", "week", "team"], how="left")

# ---- rolling pre-game rates
def rate_table(num, den, side):
    """dict[(season,week,team)] -> pre-game shrunk rate. off = team's own, def = rate allowed by team."""
    key = "team" if side == "off" else "opp"
    lg = tg[num].sum() / max(tg[den].sum(), 1)     # league constant (negligible leakage)
    avg_den = tg[den].mean()
    res = {}
    for team, d in tg.groupby(key):
        for y in YEARS:
            dp = d[d.season == y - 1]; dc = d[d.season == y]
            sc = min(PRIOR_W, len(dp)) / max(len(dp), 1)
            for w in sorted(tg[tg.season == y].week.unique()):
                c = dc[dc.week < w]
                numr = c[num].sum() + dp[num].sum() * sc
                denr = c[den].sum() + dp[den].sum() * sc
                res[(y, w, team)] = (numr + lg * K * avg_den) / (denr + K * avg_den)
    return res

tg["sack_hit"] = tg.sacks + tg.hits
R = {}
R["off3"] = rate_table("t3_c", "t3_n", "off")
R["def3"] = rate_table("t3_c", "t3_n", "def")
R["offgo"] = rate_table("f4_go", "f4_n", "off")
R["defgo"] = rate_table("f4_go", "f4_n", "def")   # how often opponents go vs this D (sit-dependent)
R["off4c"] = rate_table("f4_c", "f4_go", "off")
R["def4c"] = rate_table("f4_c", "f4_go", "def")
R["offprot"] = rate_table("sack_hit", "db_n", "off")   # pressure-ish allowed by offense
R["defprs"] = rate_table("sack_hit", "db_n", "def")    # pressure-ish generated by defense

# time to throw: simple expanding mean per team (current + prior)
def ttt_pre(y, w, team):
    d = tg[(tg.team == team) & (((tg.season == y) & (tg.week < w)) | (tg.season == y - 1))].dropna(subset=["ttt"])
    return d.ttt.mean() if len(d) else np.nan

g["mkt_margin"] = g.spread_line          # home margin implied by market
g["margin"] = g.home_score - g.away_score
g["resid"] = g.margin - g.mkt_margin      # + means home beat market
g["tot"] = g.home_score + g.away_score
g["tresid"] = g.tot - g.total_line
f = []
for _, r in g.iterrows():
    y, w, h, a = r.season, r.week, r.home_team, r.away_team
    try:
        e = {}
        for side, (o, d_) in {"h": (h, a), "a": (a, h)}.items():
            e[f"{side}_3"] = R["off3"][(y, w, o)] + R["def3"][(y, w, d_)]
            e[f"{side}_go"] = R["offgo"][(y, w, o)]
            e[f"{side}_4c"] = R["off4c"][(y, w, o)] + R["def4c"][(y, w, d_)]
            e[f"{side}_prs"] = R["offprot"][(y, w, o)] + R["defprs"][(y, w, d_)]
            e[f"{side}_ttt"] = ttt_pre(y, w, o)
        f.append({**r.to_dict(), **e})
    except KeyError:
        pass
F = pd.DataFrame(f)
F = F[F.week >= 5]   # need some current-season sample
F["d3"] = F.h_3 - F.a_3
F["d4go"] = F.h_go - F.a_go
F["d4c"] = F.h_4c - F.a_4c
F["dprs"] = F.h_prs - F.a_prs          # + = home QB under more pressure
F["dttt"] = F.h_ttt - F.a_ttt          # + = home QB holds ball longer
# interaction: long time to throw x pressure = trouble
F["h_sack_risk"] = (F.h_ttt - 2.75) * (F.h_prs - F.h_prs.mean())
F["a_sack_risk"] = (F.a_ttt - 2.75) * (F.a_prs - F.a_prs.mean())
F["dsack"] = F.h_sack_risk - F.a_sack_risk
F["tot3"] = F.h_3 + F.a_3
F["tot_prs"] = F.h_prs + F.a_prs
F.to_csv(f"{D}/situational_features.csv", index=False)

def ols(df, ycol, xs):
    d = df.dropna(subset=[ycol] + xs)
    X = np.column_stack([np.ones(len(d))] + [d[x] for x in xs]); y = d[ycol].values
    b, *_ = np.linalg.lstsq(X, y, rcond=None)
    res = y - X @ b; s2 = res @ res / (len(y) - X.shape[1])
    se = np.sqrt(np.diag(s2 * np.linalg.inv(X.T @ X)))
    return len(d), dict(zip(["const"] + xs, zip(b.round(3), (b / se).round(2))))
print("games used:", len(F), "seasons", sorted(F.season.unique()))
print("\n== Does it explain home margin vs closing line? (resid = margin - spread) ==")
for xs in (["d3"], ["d4go"], ["d4c"], ["dprs"], ["dttt"], ["dsack"], ["d3", "d4go", "d4c", "dprs", "dttt"]):
    print(xs, ols(F, "resid", xs))
print("\n== Totals vs closing total ==")
for xs in (["tot3"], ["tot_prs"], ["tot3", "tot_prs"]):
    print(xs, ols(F, "tresid", xs))
# out-of-sample: fit on 2022-2024, test 2025-2026
tr, te = F[F.season <= 2024].dropna(subset=["resid", "d3", "d4go", "d4c", "dprs", "dttt"]), F[F.season >= 2025].dropna(subset=["resid", "d3", "d4go", "d4c", "dprs", "dttt"])
xs = ["d3", "d4go", "d4c", "dprs", "dttt"]
X = np.column_stack([np.ones(len(tr))] + [tr[x] for x in xs]); b, *_ = np.linalg.lstsq(X, tr.resid.values, rcond=None)
pred = np.column_stack([np.ones(len(te))] + [te[x] for x in xs]) @ b
print("\nOOS (train<=2024, test 2025-26): n=%d corr(pred,resid)=%.3f" % (len(te), np.corrcoef(pred, te.resid)[0, 1]))
te = te.assign(pred=pred)
for thr in (0.5, 1.0, 1.5):
    s = te[te.pred.abs() >= thr]
    side = np.sign(s.pred); w = ((s.resid * side) > 0).sum(); l = ((s.resid * side) < 0).sum()
    print(f"  |edge|>={thr}: {w}-{l}  win%={w/max(w+l,1):.1%}  (breakeven 52.4%)")
